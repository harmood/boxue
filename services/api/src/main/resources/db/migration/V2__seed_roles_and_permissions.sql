-- ---------------------------------------------------------------------
-- 角色权限关系
-- USER：基础权限
-- ADMIN：全部权限（含 USER_BASIC）
-- ---------------------------------------------------------------------
INSERT INTO app_role_permission (role_id, permission_id)
SELECT r.id, p.id
FROM app_role r
JOIN app_permission p
  ON (r.code = 'USER'  AND p.code = 'USER_BASIC')
  OR (r.code = 'ADMIN')
ON CONFLICT (role_id, permission_id) DO NOTHING;

